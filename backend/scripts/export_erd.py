"""Generate docs/diagrams/erd.puml from the SQLAlchemy models, so the ERD always matches the
database schema (Alembic migrations are checked against the same models in the tests).

    python -m scripts.export_erd            # `make diagrams` also renders the PNG
"""

import sys
from pathlib import Path

from sqlalchemy import Column, Enum, Table
from sqlalchemy.dialects.postgresql.psycopg import PGDialect_psycopg

from app.core.database import Base
from app.models import __all__ as _models  # noqa: F401  (registers every table)

DIALECT = PGDialect_psycopg()  # type: ignore[no-untyped-call]
OUT = Path(__file__).resolve().parents[2] / "docs" / "diagrams" / "erd.puml"


def column_type(column: Column[object]) -> str:
    kind = column.type
    if isinstance(kind, Enum):
        return f"enum {kind.name}"
    text = kind.compile(dialect=DIALECT)
    return text.lower().replace("timestamp with time zone", "timestamptz")


def entity(table: Table) -> list[str]:
    lines = [f'entity "{table.name}" as {table.name} {{']
    pk = [c for c in table.columns if c.primary_key]
    for c in pk:
        lines.append(f"  * **{c.name}** : {column_type(c)} <<PK>>")
    lines.append("  --")
    for c in table.columns:
        if c.primary_key:
            continue
        marks = []
        if c.foreign_keys:
            marks.append("FK")
        if c.unique:
            marks.append("unique")
        if c.computed is not None:
            marks.append("generated")
        flag = "" if c.nullable else "* "
        suffix = f" <<{', '.join(marks)}>>" if marks else ""
        lines.append(f"  {flag}{c.name} : {column_type(c)}{suffix}")
    lines.append("}")
    return lines


def render() -> str:
    tables = sorted(Base.metadata.tables.values(), key=lambda t: t.name)
    lines = [
        "@startuml erd",
        "' GENERATED by backend/scripts/export_erd.py from the SQLAlchemy models. Do not edit.",
        "title Database schema (PostgreSQL 16)",
        "hide circle",
        "skinparam linetype ortho",
        "skinparam shadowing false",
        "skinparam defaultFontName Helvetica",
        "",
    ]
    for table in tables:
        lines += [*entity(table), ""]
    for table in tables:
        for fk in sorted(table.foreign_keys, key=lambda f: f.parent.name):
            target = fk.column.table.name
            column = fk.parent
            # parent side: exactly one (required FK) or zero-or-one (nullable FK);
            # child side: zero-or-one when the FK is unique or the whole key, else zero-or-many.
            parent = "|o" if column.nullable else "||"
            one_to_one = column.unique or (column.primary_key and len(table.primary_key) == 1)
            child = "o|" if one_to_one else "o{"
            lines.append(f"{target} {parent}--{child} {table.name} : {column.name}")
    lines += ["", "@enduml", ""]
    return "\n".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("docs/diagrams/erd.puml is outdated: run `make diagrams`")
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT} ({len(Base.metadata.tables)} tables)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
