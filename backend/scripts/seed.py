import os
import sys
from dataclasses import dataclass, field
from datetime import UTC, datetime, timedelta
from typing import Any

from sqlalchemy import select, text
from sqlalchemy.orm import Session, sessionmaker

from app.core.config import Settings, get_settings
from app.core.database import build_engine, build_session_factory
from app.core.security import hash_password
from app.models import (
    AuditLog,
    Bug,
    BugAssignment,
    BugStatus,
    CloseReason,
    Notification,
    ProjectRole,
    ResolutionHistory,
    Severity,
    User,
    UserRole,
)
from app.schemas.admin import ProfileCreate
from app.schemas.bug import BugCreate, TransitionRequest
from app.schemas.project import MemberAdd, ProjectCreate
from app.services import bug_service, profile_service, project_service
from app.services.access import ProjectAccess, project_access
from scripts.seed_data import BUGS, PROFILES, PROJECTS, USERS

TABLES = (
    "notification, system_setting, resolution_history, bug_assignment, profile_component, "
    "profile_skill, developer_profile, audit_log, attachment, comment, bug, project_member, "
    'project, "user"'
)


UNSET = "generated-by-make-env"  # placeholder value from .env.example


class SeedError(RuntimeError):
    pass


@dataclass(frozen=True)
class Plan:
    """Typed view of the plan tuples in seed_data.BUGS."""

    kind: str
    days_ago: int
    developers: tuple[str, ...] = ()
    original: str = ""
    hours_to_assign: int = 0
    hours_to_fix: int = 0

    @classmethod
    def parse(cls, raw: tuple[Any, ...]) -> "Plan":
        kind, target, days_ago = raw[0], raw[1], int(raw[2])
        if kind in ("duplicate_open", "duplicate_closed"):
            return cls(kind, days_ago, original=str(target))
        if kind == "tossed":
            return cls(kind, days_ago, developers=tuple(target))
        if kind == "open":
            return cls(kind, days_ago)
        return cls(kind, days_ago, (str(target),), "", int(raw[3]), int(raw[4]))


@dataclass
class Timeline:
    created: datetime
    assigned: datetime | None = None
    reassigned: datetime | None = None
    resolved: datetime | None = None
    verified: datetime | None = None
    reopened: datetime | None = None
    closed: datetime | None = None


@dataclass
class SeedSummary:
    users: dict[str, User] = field(default_factory=dict)
    projects: dict[str, int] = field(default_factory=dict)
    bugs: dict[str, int] = field(default_factory=dict)
    duplicate_pairs: list[tuple[int, int]] = field(default_factory=list)
    profiles: dict[str, tuple[int, bool]] = field(default_factory=dict)


def _access(db: Session, user: User, project_id: int) -> ProjectAccess:
    return project_access(db, user, project_id, write=True)


def _move(db: Session, bug_id: int, actor: User, to: BugStatus, **extra: object) -> None:
    bug = db.get(Bug, bug_id)
    assert bug is not None  # noqa: S101 (created a moment ago)
    request = TransitionRequest.model_validate({"to_status": to, **extra})
    bug_service.transition(db, bug, _access(db, actor, bug.project_id), request)


def _assign(db: Session, bug_id: int, pm: User, developer: User) -> None:
    bug = db.get(Bug, bug_id)
    assert bug is not None  # noqa: S101
    bug_service.assign(db, bug, _access(db, pm, bug.project_id), developer.id)


def _retime(db: Session, bug_id: int, t: Timeline) -> None:
    """Spread one bug's events over realistic times (services stamp everything 'now')."""
    bug = db.get(Bug, bug_id)
    assert bug is not None  # noqa: S101
    last = max(x for x in vars(t).values() if x is not None)
    bug.created_at = t.created
    bug.updated_at = last
    bug.resolved_at = t.resolved if bug.resolved_at is not None else None
    bug.closed_at = t.closed if bug.closed_at is not None else None

    status_times = {
        BugStatus.IN_PROGRESS.value: t.reopened or t.assigned,
        BugStatus.RESOLVED.value: t.resolved,
        BugStatus.VERIFIED.value: t.verified,
        BugStatus.CLOSED.value: t.closed,
    }
    seen_in_progress = False
    for entry in db.scalars(
        select(AuditLog).where(AuditLog.bug_id == bug_id).order_by(AuditLog.id)
    ):
        when: datetime | None = t.created
        if entry.action == "severity_overridden":
            when = t.created + timedelta(minutes=20)
        elif entry.action == "assigned":
            when = t.assigned
        elif entry.action == "reassigned":
            when = t.reassigned
        elif entry.action == "status_changed" and entry.new_value is not None:
            when = status_times.get(entry.new_value)
            if entry.new_value == BugStatus.IN_PROGRESS.value and not seen_in_progress:
                when, seen_in_progress = t.assigned, True
        elif entry.field in ("close_reason", "duplicate_of"):
            when = t.closed
        entry.created_at = when or t.created

    assignments = db.scalars(
        select(BugAssignment).where(BugAssignment.bug_id == bug_id).order_by(BugAssignment.id)
    ).all()
    starts = [t.assigned, t.reassigned]
    for index, assignment in enumerate(assignments):
        assignment.assigned_at = starts[index] or t.created
        if assignment.ended_at is not None:
            assignment.ended_at = (
                starts[index + 1] if index + 1 < len(assignments) else t.closed
            ) or last
    for history in db.scalars(select(ResolutionHistory).where(ResolutionHistory.bug_id == bug_id)):
        assert t.assigned is not None and t.resolved is not None  # noqa: S101
        history.assigned_at = t.assigned
        history.resolved_at = t.resolved
        history.resolution_hours = round((t.resolved - t.assigned).total_seconds() / 3600, 3)


def run(
    session_factory: sessionmaker[Session], settings: Settings, password: str, reset: bool = False
) -> SeedSummary:
    if settings.app_env == "production":
        raise SeedError("Refusing to seed a production database")
    summary = SeedSummary()
    now = datetime.now(UTC).replace(minute=0, second=0, microsecond=0)

    with session_factory() as db:
        if reset:
            db.execute(text(f"TRUNCATE {TABLES} RESTART IDENTITY CASCADE"))
            db.commit()
        elif db.scalar(select(User.id).limit(1)) is not None:
            raise SeedError("The database already has data; use `make seed-reset` to replace it")

        password_hash = hash_password(password, settings.bcrypt_rounds)
        for key, name, email, role in USERS:
            user = User(
                email=email, full_name=name, password_hash=password_hash, role=UserRole(role)
            )
            db.add(user)
            summary.users[key] = user
        db.commit()
        users = summary.users
        pm, admin = users["pm"], users["admin"]
        reporters = [users["rita"], users["quinn"]]

        for name, description, members in PROJECTS:
            project = project_service.create_project(
                db, pm, ProjectCreate(name=name, description=description)
            )
            summary.projects[name] = project.id
            for member_key, role in members.items():
                project_service.add_member(
                    db,
                    _access(db, pm, project.id),
                    MemberAdd(user_id=users[member_key].id, role=ProjectRole(role)),
                )

        for index, (
            key,
            project_name,
            title,
            description,
            steps,
            environment,
            components,
            severity,
            raw_plan,
        ) in enumerate(BUGS):
            project_id = summary.projects[project_name]
            reporter = reporters[index % 2]
            bug = bug_service.create_bug(
                db,
                _access(db, reporter, project_id),
                reporter,
                BugCreate(
                    project_id=project_id,
                    title=title,
                    description=description,
                    steps_to_reproduce=steps,
                    environment=environment,
                    components=components,
                ),
            )
            summary.bugs[key] = bug.id
            bug_service.override_severity(db, bug, _access(db, pm, project_id), Severity(severity))

            plan = Plan.parse(raw_plan)
            created = now - timedelta(days=plan.days_ago, hours=(index * 5) % 9 + 1)
            t = Timeline(created=created)
            if plan.kind in ("closed", "resolved", "verified", "in_progress", "reopened"):
                developer = users[plan.developers[0]]
                assigned = created + timedelta(hours=plan.hours_to_assign)
                resolved = assigned + timedelta(hours=plan.hours_to_fix)
                t.assigned = assigned
                _assign(db, bug.id, pm, developer)
                if plan.kind != "in_progress":
                    t.resolved = resolved
                    _move(db, bug.id, developer, BugStatus.RESOLVED)
                if plan.kind in ("closed", "verified"):
                    t.verified = resolved + timedelta(hours=4)
                    _move(db, bug.id, reporter, BugStatus.VERIFIED)
                if plan.kind == "closed":
                    t.closed = resolved + timedelta(hours=6)
                    _move(db, bug.id, pm, BugStatus.CLOSED)
                if plan.kind == "reopened":
                    t.reopened = resolved + timedelta(hours=6)
                    _move(db, bug.id, reporter, BugStatus.IN_PROGRESS)
            elif plan.kind == "tossed":
                first, second = (users[k] for k in plan.developers)
                t.assigned = created + timedelta(hours=2)
                t.reassigned = created + timedelta(hours=22)
                _assign(db, bug.id, pm, first)
                _assign(db, bug.id, pm, second)
            elif plan.kind == "duplicate_closed":
                original = summary.bugs[plan.original]
                t.closed = created + timedelta(hours=1)
                _move(
                    db,
                    bug.id,
                    pm,
                    BugStatus.CLOSED,
                    close_reason=CloseReason.DUPLICATE,
                    duplicate_of_id=original,
                )
                summary.duplicate_pairs.append((original, bug.id))
            elif plan.kind == "duplicate_open":
                summary.duplicate_pairs.append((summary.bugs[plan.original], bug.id))
            _retime(db, bug.id, t)
            db.commit()

        for key, (skills, components, languages, level, availability, workload) in PROFILES.items():
            profile = profile_service.create_profile(
                db,
                admin,
                ProfileCreate.model_validate(
                    {
                        "user_id": users[key].id,
                        "skills": skills,
                        "components": components,
                        "languages": languages,
                        "experience_level": level,
                        "availability": availability,
                        "max_workload": workload,
                    }
                ),
            )
            summary.profiles[key] = (profile.resolved_count, profile.is_cold_start)

        # Seeding is not news: drop the alerts the services queued (they were never delivered).
        db.query(Notification).delete()
        db.commit()
    return summary


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--reset", action="store_true", help="delete all data first")
    args = parser.parse_args()
    password = os.environ.get("SEED_PASSWORD", "")
    if not password or password == UNSET:
        print("SEED_PASSWORD is not set. Run `make env` first.", file=sys.stderr)
        return 2
    settings = get_settings()
    engine = build_engine(settings)
    try:
        summary = run(build_session_factory(engine), settings, password, reset=args.reset)
    except SeedError as exc:
        print(exc, file=sys.stderr)
        return 1
    finally:
        engine.dispose()

    print(f"Seeded {len(summary.bugs)} bugs in {len(summary.projects)} projects.\n")
    print("Accounts (password = SEED_PASSWORD in .env):")
    for key, name, email, role in USERS:
        note = ""
        if key in summary.profiles:
            resolved, cold = summary.profiles[key]
            note = f"  resolved={resolved}{'  COLD START' if cold else ''}"
        print(f"  {role:<15} {name:<14} {email}{note}")
    pairs = ", ".join(f"#{a}~#{b}" for a, b in summary.duplicate_pairs)
    print(f"\nDuplicate pairs (original~duplicate): {pairs}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
