"""Load demo data: users for all four roles, two projects, 50 bugs, developer profiles.

    make seed          # inside the backend container, refuses to run on a non-empty database
    make seed-reset    # wipes all application data first

Everything is created through the same service functions the API uses, so audit trail,
assignment/resolution history and cold-start counters are consistent. Afterwards the
timestamps are spread over the last 60 days so the dashboard and statistics look realistic.
The password of every account is SEED_PASSWORD from .env (generated by `make env`).
"""

