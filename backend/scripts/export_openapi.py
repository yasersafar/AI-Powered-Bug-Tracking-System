"""Export the API description (NFR-13, DC-05).

    python -m scripts.export_openapi        # from backend/; `make openapi`

FastAPI generates OpenAPI 3.1. The design constraint asks for OpenAPI 3.0, so this script
writes two validated files:

* docs/openapi.json      OpenAPI 3.0.3, converted from the generated document
* docs/openapi-3.1.json  the document exactly as FastAPI generates it

Conversion (JSON Schema 2020-12 -> OpenAPI 3.0 schema object): `anyOf [X, null]` and
`type: [X, "null"]` become `nullable: true`; `const` becomes a one-value `enum`; schema
`examples` lists become `example`; numeric `exclusiveMinimum/Maximum` become the 3.0
boolean form; `contentMediaType` (file uploads) becomes `format: binary`; a `$ref` with
sibling keywords is wrapped in `allOf`; `propertyNames` is moved into the description.
"""

import argparse
import json
import sys
from copy import deepcopy
from pathlib import Path
from typing import Any

from openapi_spec_validator import validate

from app.core.config import Settings
from app.main import create_app

DOCS = Path(__file__).resolve().parents[2] / "docs"
# Schemas generated by FastAPI itself (form bodies, validation errors, generic pages).
FRAMEWORK_DESCRIPTIONS = {
    "Body_login_api_v1_auth_login_post": "OAuth2 password form: `username` is the e-mail.",
    "Body_upload_attachment_api_v1_bugs__bug_id__attachments_post": "Multipart file upload "
    "(<= 10 MB; images, PDF, text and logs; the real MIME type is checked).",
    "HTTPValidationError": "FastAPI's validation error model. This API returns validation "
    "errors as ErrorResponse with code `validation_error` and the field errors in `details`.",
    "ValidationError": "One field error: location, message and type.",
    "Page_BugListItem_": "One page of bugs; `total` counts all matches.",
    "Page_NotificationRead_": "One page of notifications; `total` counts all matches.",
    "Page_UserSummary_": "One page of users; `total` counts all matches.",
}
SERVERS = [
    {"url": "http://localhost:8000", "description": "Local development (docker compose)"},
]


def _schema_30(node: Any) -> Any:
    if isinstance(node, list):
        return [_schema_30(item) for item in node]
    if not isinstance(node, dict):
        return node
    node = {key: _schema_30(value) for key, value in node.items()}

    for key in ("anyOf", "oneOf"):
        options = node.get(key)
        if isinstance(options, list) and {"type": "null"} in options:
            rest = [o for o in options if o != {"type": "null"}]
            node.pop(key)
            if len(rest) == 1 and "$ref" not in rest[0]:
                node = {**rest[0], **node}
            elif len(rest) == 1:
                node["allOf"] = rest
            else:
                node[key] = rest
            node["nullable"] = True

    kind = node.get("type")
    if isinstance(kind, list):
        others = [t for t in kind if t != "null"]
        node["type"] = others[0] if len(others) == 1 else others
        if "null" in kind:
            node["nullable"] = True
    if "const" in node:
        node["enum"] = [node.pop("const")]
    if isinstance(node.get("examples"), list):
        examples = node.pop("examples")
        if examples:
            node["example"] = examples[0]
    for bound, plain in (("exclusiveMinimum", "minimum"), ("exclusiveMaximum", "maximum")):
        if isinstance(node.get(bound), (int, float)) and not isinstance(node[bound], bool):
            node[plain] = node.pop(bound)
            node[bound] = True
    if "contentMediaType" in node:
        node.pop("contentMediaType")
        node["format"] = "binary"
    if "propertyNames" in node:  # not in 3.0: keep the allowed keys as documentation
        names = node.pop("propertyNames")
        if isinstance(names, dict) and "enum" in names:
            note = "Keys: " + ", ".join(str(k) for k in names["enum"]) + "."
            node["description"] = f"{node.get('description', '')} {note}".strip()
    if "$ref" in node and len(node) > 1:  # 3.0 ignores keywords next to $ref
        ref = node.pop("$ref")
        node = {"allOf": [{"$ref": ref}], **node}
    return node


def to_openapi_30(spec: dict[str, Any]) -> dict[str, Any]:
    out = deepcopy(spec)
    out["openapi"] = "3.0.3"
    out.pop("jsonSchemaDialect", None)
    out.pop("webhooks", None)
    components = out.get("components", {})
    components["schemas"] = {
        name: _schema_30(schema) for name, schema in components.get("schemas", {}).items()
    }
    for operations in out.get("paths", {}).values():
        for operation in operations.values():
            for parameter in operation.get("parameters", []):
                if "schema" in parameter:
                    parameter["schema"] = _schema_30(parameter["schema"])
            for container in [
                operation.get("requestBody", {}),
                *operation.get("responses", {}).values(),
            ]:
                for media in container.get("content", {}).values():
                    if "schema" in media:
                        media["schema"] = _schema_30(media["schema"])
    return out


def build() -> dict[str, Any]:
    settings = Settings(app_env="production", ml_enabled=False, cors_origins=[])
    spec: dict[str, Any] = create_app(settings).openapi()
    spec["servers"] = SERVERS
    for name, text in FRAMEWORK_DESCRIPTIONS.items():
        schema = spec.get("components", {}).get("schemas", {}).get(name)
        if schema is not None:
            schema.setdefault("description", text)
    return spec


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if the files are outdated")
    args = parser.parse_args()
    original = build()
    converted = to_openapi_30(original)
    validate(original)  # raises on an invalid 3.1 document
    validate(converted)  # raises on an invalid 3.0.3 document
    outputs = {DOCS / "openapi.json": converted, DOCS / "openapi-3.1.json": original}
    stale = []
    for path, document in outputs.items():
        text = json.dumps(document, indent=2, ensure_ascii=False) + "\n"
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(path.name)
        else:
            path.write_text(text)
    if stale:
        print(f"outdated: {', '.join(stale)} (run `make openapi`)")
        return 1
    paths = sum(len(ops) for ops in converted["paths"].values())
    print(
        f"OpenAPI 3.0.3 and 3.1 valid: {len(converted['paths'])} paths, {paths} operations, "
        f"{len(converted['components']['schemas'])} schemas"
        + ("" if args.check else f" -> {DOCS / 'openapi.json'}")
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
